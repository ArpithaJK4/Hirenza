import { useEffect, useState } from "react";
import { Link, useNavigate, useParams } from "react-router-dom";
import { api } from "../api";
import { Flash, Page, Score, useAction, useApi } from "../ui";

function Detail({ id, onChange }: { id: string; onChange: () => void }) {
  const { data: d, reload } = useApi(`/api/applications/${id}`);
  const [tab, setTab] = useState<"job" | "resume" | "cover_letter" | "form">("job");
  const [draft, setDraft] = useState("");
  const [ref, setRef] = useState("");
  const a = useAction();
  const doc = d?.documents?.find((x: any) => x.kind === tab);
  useEffect(() => setDraft(doc?.content ?? ""), [doc?.content, tab]);
  if (!d) return null;
  const act = (path: string, body?: unknown, ok?: string) => a.run(async () => { await api(`/api/applications/${id}/${path}`, { method: "POST", json: body }); reload(); onChange(); }, ok);
  return (
    <div className="card space-y-3">
      <div className="flex flex-wrap items-start justify-between gap-2">
        <div><div className="font-semibold">{d.job_title}</div><div className="text-sm text-slate-500">{d.company} · via {d.source} · variant {d.resume_variant} · {d.apply_method}</div></div>
        <div className="flex items-center gap-2"><Score v={d.match_score} /><span className="chip">{d.status}</span></div>
      </div>
      <p className="text-sm text-slate-600">{d.explanation}</p>
      <div className="flex gap-1 border-b">{(["job", "resume", "cover_letter", "form"] as const).map((t) => (
        <button key={t} onClick={() => setTab(t)} className={`px-3 py-1.5 text-sm ${tab === t ? "border-b-2 border-indigo-600 font-medium" : "text-slate-500"}`}>{t.replace("_", " ")}</button>))}</div>
      {tab === "job" && <pre className="whitespace-pre-wrap text-sm font-sans max-h-96 overflow-auto">{d.description}</pre>}
      {(tab === "resume" || tab === "cover_letter") && <>
        <textarea className="input w-full h-80 font-mono text-xs" value={draft} onChange={(e) => setDraft(e.target.value)} disabled={d.status === "submitted"} />
        <div className="flex gap-2">
          <button className="btn" disabled={draft === doc?.content} onClick={() => a.run(async () => { await api(`/api/applications/${id}/documents`, { method: "PUT", json: { kind: tab, content: draft } }); reload(); }, "Saved")}>Save edits</button>
          {tab === "resume" && <a className="btn" href="#" onClick={async (e) => { e.preventDefault(); const b = await api<Blob>(`/api/applications/${id}/resume.pdf`); window.open(URL.createObjectURL(b)); }}>Preview PDF</a>}
          <span className="text-xs text-slate-400 self-center">generated by {doc?.generated_by}</span>
        </div></>}
      {tab === "form" && <div className="space-y-2">
        <div className="text-xs text-slate-500">Autofill values (from your .env): {Object.entries(d.autofill_preview).map(([k, v]) => `${k}: ${v}`).join(" · ")}</div>
        <table className="w-full"><thead><tr><th>Field</th><th>Type</th><th>Required</th></tr></thead>
          <tbody>{d.form_fields.map((f: any, i: number) => <tr key={i} className="border-t"><td>{f.label}{f.options?.length ? <div className="text-xs text-slate-400">{f.options.join(" / ")}</div> : null}</td><td className="text-xs">{f.type}</td><td>{f.required ? "yes" : ""}</td></tr>)}</tbody></table>
      </div>}
      <Flash msg={a.msg} err={a.err} />
      <div className="flex flex-wrap gap-2 border-t pt-3">
        {d.status === "prepared" && <>
          <button className="btn btn-primary" disabled={a.busy} onClick={() => act("approve", undefined, "Approved — now submit it")}>✓ Approve</button>
          <button className="btn btn-danger" disabled={a.busy} onClick={() => act("reject", { reason: "" }, "Rejected")}>✕ Reject</button></>}
        {d.status === "approved" && <div className="space-y-2 w-full">
          <div className="text-sm">Submit it yourself: <a className="underline" href={d.apply_url} target="_blank" rel="noreferrer">open application ↗</a>
            {d.apply_method === "autofill" && <> or run <code className="chip">python -m app.cli autofill {d.id}</code> (fills the form, you click submit)</>}</div>
          <div className="flex gap-2"><input className="input flex-1" placeholder="Confirmation reference (email subject / portal ID)" value={ref} onChange={(e) => setRef(e.target.value)} />
            <button className="btn btn-primary" disabled={ref.length < 3 || a.busy} onClick={() => act("submitted", { confirmation_ref: ref, source: "user_attested" }, "Recorded as submitted")}>I submitted it</button></div>
        </div>}
        {d.status === "submitted" && <div className="text-sm text-emerald-700">Submitted · ref {d.confirmation_ref} · tracked in <Link className="underline" to="/tracker">Tracker</Link></div>}
      </div>
    </div>
  );
}

export default function Review() {
  const { id } = useParams();
  const nav = useNavigate();
  const [status, setStatus] = useState("prepared");
  const { data, reload } = useApi<any[]>(`/api/applications?status=${status}`);
  return (
    <Page title="Application Review Queue" actions={
      <select className="input" value={status} onChange={(e) => setStatus(e.target.value)}>
        {["prepared", "approved", "submitted", "rejected"].map((s) => <option key={s}>{s}</option>)}</select>}>
      <div className="grid lg:grid-cols-3 gap-4">
        <div className="card p-0 divide-y">
          {data?.map((x) => (
            <button key={x.id} onClick={() => nav(`/review/${x.id}`)} className={`w-full text-left p-3 flex gap-3 hover:bg-slate-50 ${String(x.id) === id ? "bg-indigo-50" : ""}`}>
              <Score v={x.match_score} /><div className="min-w-0"><div className="truncate text-sm font-medium">{x.job_title}</div><div className="truncate text-xs text-slate-500">{x.company}</div></div>
            </button>))}
          {!data?.length && <p className="p-3 text-sm text-slate-500">Nothing here. Prepare applications from a job page.</p>}
        </div>
        <div className="lg:col-span-2">{id ? <Detail key={id} id={id} onChange={reload} /> : <div className="card text-sm text-slate-500">Select an application.</div>}</div>
      </div>
    </Page>
  );
}
